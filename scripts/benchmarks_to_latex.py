"""Turn results/benchmarks.json into the benchmark section of the LaTeX report.

Writes docs/report/benchmarks.tex (a fragment \\input by strategy_report.tex)
and docs/report/figures/openmp_scaling.png. Re-run after
`python scripts/run_benchmarks.py` to refresh the report with new numbers.

Usage:
    python scripts/benchmarks_to_latex.py
"""
from __future__ import annotations

import json
